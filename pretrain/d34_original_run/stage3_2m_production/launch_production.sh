#!/bin/bash
# Start the stage-3 production chain (step 137,340 -> 229,067 at batch 2,097,152; ~10 x 24-h legs on one 8-GPU node).
# Writes the placement file that every leg resubmits its successor with, then queues leg 1 of production_leg.sbatch.
# usage: D34_CONFIG=... bash launch_production.sh            (after prepare_corpus.sbatch and prepare_release.sbatch)
set -euo pipefail
source "${D34_CONFIG:?export D34_CONFIG=/absolute/path/to/config.sh}"
for f in "$D34_PROD_RELEASE" "$D34_FULL_CORPUS_RECEIPT" "$D34_ASSET_RECEIPT" "$D34_RECEIPTS/winner_completion.sha256"; do
  [ -f "$f" ] || { echo "missing $f: run prepare_corpus.sbatch and prepare_release.sbatch first"; exit 2; }
done
mkdir -p "$D34_PROD_DIR"
# One sbatch argument per line; production_leg.sbatch reads it without shell evaluation. Later arguments win, so
# $D34_GPU_SBATCH can override the defaults above it. --mail-type is set here because the leg script is frozen code.
{
  echo "# generated by launch_production.sh from $D34_CONFIG on $(date -Is)"
  printf '%s\n' "--nodes=$D34_PROD_NODES" --ntasks-per-node=1 --cpus-per-task=48 --mem=0 --time=24:00:00 --no-requeue \
    --mail-type=NONE --job-name=d34prod "--output=$D34_PROD_DIR/slurm-%j.out"
  for a in $D34_GPU_SBATCH; do echo "$a"; done
} > "$D34_PROD_SBATCH_ARGS_FILE"
placement=()
while IFS= read -r argument; do
  [[ -z "$argument" || "$argument" == \#* ]] || placement+=("$argument")
done < "$D34_PROD_SBATCH_ARGS_FILE"
J=$(sbatch --parsable "${placement[@]}" --export="ALL,D34_PROD_CONFIG=$D34_CONFIG" "$D34_PRODUCTION_CODE/production_leg.sbatch")
echo "production leg 1 = job $J; log $D34_PROD_DIR/chain.log, metrics $D34_PROD_DIR/metrics.jsonl"
sleep 3; squeue -h -j "${J%%;*}" --start -o "est. start %S (%R)" || true
